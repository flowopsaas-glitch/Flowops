#!/usr/bin/env python3
"""
Generate the RLS tenant-isolation migration from schema.prisma.

Every model that carries a `companyId` column gets:
  - ENABLE + FORCE ROW LEVEL SECURITY (FORCE because the app's DB user owns the
    tables; without it policies would not apply to the owner)
  - a `tenant_isolation` policy bound to the session-local `app.company_id` GUC

Phase-1 semantics (safe rollout): when `app.company_id` is NOT set (legacy call
sites, seeds, the cross-tenant outbox drain), the policy steps aside and the
existing app-level filters remain the boundary — the platform cannot break.
When it IS set (the `withTenant()` path), the DATABASE enforces isolation on
every query, defence-in-depth style.

Phase-2 (later, once every call site sets context): drop the
`OR app_tenant() IS NULL` clause in a one-line follow-up migration.

Regenerate:  python3 backend/scripts/generate-rls-migration.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "prisma" / "schema.prisma"
OUT = ROOT / "prisma" / "migrations" / "20261012210000_rls_tenant_isolation" / "migration.sql"

POLICY = """-- {table}
ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "{table}" FORCE ROW LEVEL SECURITY;
CREATE POLICY "tenant_isolation" ON "{table}"
  USING (app_tenant_guard("companyId"))
  WITH CHECK (app_tenant_guard("companyId"));"""


def tenant_tables(schema_text: str) -> list[str]:
    models = re.findall(r"model (\w+) \{(.*?)\n\}", schema_text, re.S)
    tables = []
    for _name, body in models:
        if not re.search(r'^\s*companyId\s+String', body, re.M):
            continue
        m = re.search(r'@@map\("([^"]+)"\)', body)
        tables.append(m.group(1) if m else _name)
    return sorted(tables)


def main() -> int:
    tables = tenant_tables(SCHEMA.read_text())
    header = f"""-- Row-Level Security: tenant isolation on every table carrying a companyId
-- ({len(tables)} tables). Generated by backend/scripts/generate-rls-migration.py —
-- regenerate rather than hand-edit. Companion test:
-- backend/src/db/rls-policy-coverage.spec.ts fails if a tenant table lacks a policy.
--
-- SEMANTICS (the whole point — read before changing):
--
--   app.company_id set     -> the DATABASE enforces isolation: only rows of that
--                             tenant are visible/updatable, whatever the app does.
--   app.company_id unset   -> behaviour depends on the app.rls_strict flag:
--
--     rls_strict off/empty (PHASE-1, default)  -> the policy steps aside and the
--                             app-level filters remain the boundary. Zero
--                             regression for seeds, migrations, the cross-tenant
--                             outbox drain and legacy call sites.
--     rls_strict 'on'      (PHASE-2)          -> rows WITHOUT a tenant context are
--                             refused outright. Every path must run inside
--                             PrismaService.withTenant(companyId, ...).
--
-- PHASE-2 IS A SETTING FLIP, NOT A MIGRATION:
--     ALTER DATABASE flowops SET app.rls_strict = 'on';
-- (or set app.rls_strict per role/session). Flip once every call site establishes
-- tenant context; flip back with 'off' if anything misbehaves.

CREATE OR REPLACE FUNCTION app_tenant() RETURNS TEXT
STABLE
LANGUAGE sql
AS $$ SELECT NULLIF(current_setting('app.company_id', true), '') $$;

-- The guard every policy binds to. Deliberately a function (not an inlined
-- expression) so the semantics live in exactly one place and can be reasoned
-- about — and so the coverage test can pin its shape.
CREATE OR REPLACE FUNCTION app_tenant_guard("companyId" TEXT) RETURNS BOOLEAN
STABLE
LANGUAGE sql
AS $$
  SELECT "companyId" = app_tenant()
      OR (
        app_tenant() IS NULL
        AND NOT COALESCE(current_setting('app.rls_strict', true), 'off') IN ('on', 'true', '1')
      )
$$;
"""
    body = "\n\n".join(POLICY.format(table=t) for t in tables)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "\n" + body + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} — {len(tables)} tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
