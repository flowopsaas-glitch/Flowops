import { Injectable, Logger } from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';
import PDFDocument from 'pdfkit'; // 🚀 FIXED: Changed from * as PDFDocument
import * as bwipjs from 'bwip-js';

@Injectable()
export class ManifestService {
  private readonly logger = new Logger(ManifestService.name);

  constructor(private prisma: PrismaService) {}

  async generatePDF(manifestId: number): Promise<Buffer> {
    const manifest = await this.prisma.linehaulManifest.findUnique({
      where: { id: manifestId },
      include: {
        sourceBranch: true,
        destinationBranch: true,
        waybills: true,
      },
    });

    if (!manifest) throw new Error('Manifest not found');

    return new Promise(async (resolve, reject) => {
      // 🏗️ The constructor will now be recognized correctly
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const buffers: Buffer[] = [];

      doc.on('data', buffers.push.bind(buffers));
      doc.on('end', () => resolve(Buffer.concat(buffers)));

      // --- BRANDING & HEADER ---
      doc.fillColor('#1d4ed8').fontSize(28).font('Helvetica-Bold').text('FLOWOPS', 50, 50);
      doc.fillColor('#64748b').fontSize(8).font('Helvetica').text('LOGISTICS COMMAND CENTER', 50, 80);
      
      doc.fillColor('#000000').fontSize(22).font('Helvetica-Bold').text('MANIFEST', 350, 50, { align: 'right' });
      doc.fontSize(10).font('Helvetica').text(manifest.manifestNumber ?? 'N/A', 350, 80, { align: 'right' });

      doc.moveTo(50, 110).lineTo(550, 110).lineWidth(1).strokeColor('#e2e8f0').stroke();

      // --- METADATA SECTION ---
      const gridY = 130;
      doc.fillColor('#64748b').fontSize(7).font('Helvetica-Bold').text('SOURCE HUB', 50, gridY);
      doc.fillColor('#000000').fontSize(11).font('Helvetica-Bold').text((manifest.sourceBranch?.name ?? 'UNKNOWN').toUpperCase(), 50, gridY + 12);

      doc.fillColor('#64748b').text('DESTINATION HUB', 200, gridY);
      doc.fillColor('#1d4ed8').text((manifest.destinationBranch?.name ?? 'UNKNOWN').toUpperCase(), 200, gridY + 12);

      doc.fillColor('#64748b').text('ASSIGNED DRIVER', 380, gridY);
      doc.fillColor('#000000').text(
        'FLEET_AUTO', // driverId moved to ShipmentLegs in Orchestrator schema
        380,
        gridY + 12,
      );

      // --- BARCODE GENERATION ---
      try {
        const barcodeBuffer = await (bwipjs as any).toBuffer({
          bcid: 'code128',
          text: manifest.manifestNumber ?? manifest.id,
          scale: 3,
          height: 10,
          includetext: true,
          textxalign: 'center',
        });
        doc.image(barcodeBuffer, 430, 165, { width: 120 });
      } catch (err) {
        this.logger.error('Barcode failure', err);
      }

      // --- WAYBILL TABLE ---
      const tableTop = 240;
      doc.rect(50, tableTop, 500, 20).fill('#f8fafc');
      doc.fillColor('#475569').fontSize(8).font('Helvetica-Bold');
      doc.text('WAYBILL ID', 60, tableTop + 6);
      doc.text('RECIPIENT // DESTINATION', 160, tableTop + 6);
      doc.text('WEIGHT', 400, tableTop + 6);
      doc.text('SCAN', 510, tableTop + 6);

      let rowY = tableTop + 30;
      doc.font('Helvetica').fontSize(9).fillColor('#0f172a');
      
      manifest.waybills.forEach((wb: any, i: number) => {
        if (i % 2 === 0) {
          doc.rect(50, rowY - 5, 500, 18).fill('#f1f5f9');
          doc.fillColor('#0f172a');
        }
        
        doc.text(wb.waybillNumber || 'PENDING', 60, rowY);
        doc.text(wb.recipient?.substring(0, 35) || 'Unknown', 160, rowY);
        doc.text(`${wb.weightKg} kg`, 400, rowY);
        doc.rect(510, rowY - 2, 10, 10).stroke(); // Checkbox for manual tally
        
        rowY += 18;

        if (rowY > 750) {
          doc.addPage();
          rowY = 50;
        }
      });

      // --- FOOTER ---
      doc.fontSize(7).fillColor('#94a3b8').text('GENERATED BY FLOWOPS AI SUPERVISOR', 50, 780, { align: 'center' });

      doc.end();
    });
  }
}
