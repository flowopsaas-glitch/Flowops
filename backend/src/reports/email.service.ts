import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';

@Injectable()
export class EmailService {
  private readonly logger = new Logger(EmailService.name);

  constructor(private readonly config: ConfigService) {}

  async sendReportEmail(to: string, subject: string, pdfBuffer: Buffer, fileName: string): Promise<boolean> {
    const apiKey = this.config.get('SENDGRID_API_KEY');
    
    if (!apiKey || apiKey === 'your_sendgrid_api_key') {
      this.logger.warn('⚠️  SendGrid API key not configured. Email not sent.');
      this.logger.warn(`   Would have sent to: ${to} with attachment: ${fileName} (${pdfBuffer.length} bytes)`);
      return false;
    }

    try {
      // Dynamic import to avoid errors if @sendgrid/mail isn't installed
      const sgMail = await import('@sendgrid/mail');
      sgMail.default.setApiKey(apiKey);

      const msg = {
        to,
        from: 'reports@flowops.work',
        subject,
        text: 'Please find attached your FlowOps Analytics Report.',
        html: `
          <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
            <div style="background: linear-gradient(135deg, #1e1b4b 0%, #312e81 100%); padding: 30px; border-radius: 8px 8px 0 0;">
              <h1 style="color: white; margin: 0; font-size: 24px;">FlowOps Analytics Report</h1>
              <p style="color: #c7d2fe; margin: 10px 0 0 0;">Your automated business intelligence report</p>
            </div>
            <div style="padding: 30px; background: #f9fafb;">
              <p style="color: #1f2937; font-size: 16px;">Hello,</p>
              <p style="color: #4b5563;">Please find attached your automated analytics report for the last 30 days.</p>
              <p style="color: #4b5563;">This report includes:</p>
              <ul style="color: #4b5563;">
                <li>Revenue metrics & KPIs</li>
                <li>Delivery performance analysis</li>
                <li>Top destinations & routes</li>
                <li>Predictive insights</li>
              </ul>
              <hr style="border: 1px solid #e5e7eb; margin: 20px 0;" />
              <p style="font-size: 12px; color: #6b7280;">Generated by FlowOps AI Analytics Engine</p>
            </div>
          </div>
        `,
        attachments: [
          {
            content: pdfBuffer.toString('base64'),
            filename: fileName,
            type: 'application/pdf',
            disposition: 'attachment',
          },
        ],
      };

      await sgMail.default.send(msg);
      this.logger.log(`✅ Report email sent to ${to}`);
      return true;
    } catch (error) {
      this.logger.error(`❌ Failed to send email: ${error.message}`);
      return false;
    }
  }
}
